#include "./BSP/I2C/iic.h"   // 包含上头定义好的引脚和宏

// ============================================================
// 起始信号：告诉 OLED “我要开始说话了”
// 就像打电话时先“喂”一声
// 步骤：SCL 高电平 → SDA 从高跳到低
// ============================================================
void IIC_Start(void)
{
    OLED_SDA_OUT();        // 把 SDA 引脚设为输出模式（主机要主动控制电平）
    OLED_SCL_SET();        // 先拉高时钟线（SCL=1）
    OLED_SDA_SET();        // 拉高数据线（空闲状态数据线是高电平）
    delay_us(1);           // 稍微延时，让电平稳定（给硬件反应时间）
    OLED_SDA_RESET();        // ★ 关键动作：在 SCL 为高的时候，把 SDA 从高拉低，这就是“起始信号”
    delay_us(1);           // 保持住这个状态一小会儿
    OLED_SCL_RESET();        // 最后把时钟线拉低，准备传输数据（数据只能在 SCL 低电平时改变）
}

// ============================================================
// 停止信号：告诉 OLED “我说完了”
// 就像打电话时挂电话
// 步骤：SCL 高电平 → SDA 从低跳到高
// ============================================================
void IIC_Stop(void)
{
    OLED_SDA_OUT();        // SDA 设为输出
    OLED_SCL_RESET();        // 先把时钟拉低，准备操作
    OLED_SDA_RESET();        // 把 SDA 拉低
    OLED_SCL_SET();        // 拉高 SCL，此时 SDA 还是低电平
    delay_us(1);           // 稳定一下
    OLED_SDA_SET();        // ★ 在 SCL 高的时候，把 SDA 从低拉高，就是“停止信号”
    delay_us(1);           // 保持稳定
}

// ============================================================
// 等待应答：听完别人说话后，等对方说“收到”
// 原理：主机发完一个字节后，释放 SDA，
//       从机（OLED）如果收到了，会把 SDA 拉低（表示“收到”）
// ============================================================
void IIC_Wait_Ack(void)
{
    OLED_SDA_IN();         // 把 SDA 改为输入模式，让从机可以控制 SDA
    OLED_SCL_SET();        // 拉高时钟线（在第 9 个时钟周期检测应答）
    delay_us(1);           // 等待电平稳定
    // 这时候，如果 OLED 收到了，它会主动把 SDA 拉低
    // 我们不需要在这里判断，因为 OLED 一定收得到（如果硬件没问题）
    OLED_SCL_RESET();        // 拉低时钟线，结束应答位
}

// ============================================================
// 发送一个字节（8个bit）
// 从最高位（bit7）开始发，发到最低位（bit0）
// ============================================================
void Write_IIC_Byte(uint8_t IIC_Byte)
{
    uint8_t i;
    
    OLED_SDA_OUT();        // SDA 设为输出，因为主机要发送数据
    
    for (i = 0; i < 8; i++) {              // 循环 8 次，发 8 个 bit
        if (IIC_Byte & 0x80) {              // 判断当前最高位是 1 还是 0（0x80 = 1000 0000）
            OLED_SDA_SET();                 // 如果该位是 1，把 SDA 拉高
        } else {
            OLED_SDA_RESET();                 // 如果是 0，把 SDA 拉低
        }
        OLED_SCL_SET();                     // 拉高时钟，告诉 OLED “请读取这个位！”
        delay_us(1);                        // 给 OLED 一点时间采样
        OLED_SCL_RESET();                     // 拉低时钟，准备发送下一位（数据可以在低电平期间变化）
        delay_us(1);
        IIC_Byte <<= 1;                     // 左移一位，让原本的 bit6 变成新的最高位，准备下一轮循环
    }
}

// ============================================================
// 发送命令：告诉 OLED “你要做这个动作”
// 比如：0xAE = 关闭显示，0xAF = 开启显示
// 命令的 I2C 传输格式：起始 + 从机地址 + 0x00（表示后面是命令）+ 命令值 + 停止
// ============================================================
void Write_IIC_Command(uint8_t IIC_Command)
{
    IIC_Start();                         // ① 起始信号：喂，我要开始说了
    Write_IIC_Byte(IIC_SLAVE_ADDR);      // ② 发送从机地址（0x78），相当于“OLED 在吗？”
    IIC_Wait_Ack();                      // ③ 等 OLED 回答“在”（应答）
    Write_IIC_Byte(0x00);                // ④ 发送 0x00，表示“接下来我要给你发的是命令哦”
    IIC_Wait_Ack();                      // ⑤ 等 OLED 说“好，我准备好收命令了”
    Write_IIC_Byte(IIC_Command);         // ⑥ 把真正的命令发过去（比如 0xAE）
    IIC_Wait_Ack();                      // ⑦ 等 OLED 说“收到命令”
    IIC_Stop();                          // ⑧ 停止信号：说完了，挂电话
}

// ============================================================
// 发送数据：给 OLED 显示的内容
// 比如：你要让某个像素亮起来，就发对应的数据
// 数据的 I2C 传输格式：起始 + 从机地址 + 0x40（表示后面是数据）+ 数据值 + 停止
// ============================================================
void Write_IIC_Data(uint8_t IIC_Data)
{
    IIC_Start();                         // ① 起始信号
    Write_IIC_Byte(IIC_SLAVE_ADDR);      // ② 呼叫 OLED
    IIC_Wait_Ack();                      // ③ 等待应答
    Write_IIC_Byte(0x40);                // ④ 发送 0x40，表示“接下来是数据”（而不是命令）
    IIC_Wait_Ack();                      // ⑤ 等待应答
    Write_IIC_Byte(IIC_Data);            // ⑥ 发送真正的数据（比如像素点阵）
    IIC_Wait_Ack();                      // ⑦ 等待应答
    IIC_Stop();                          // ⑧ 停止
}

