#ifndef __24CXX_H
#define __24CXX_H

#include "./SYSTEM/sys/sys.h"

/* ====================================================================
   AT24Cxx 型号定义（地址容量/字节数）
   计算公式：(1 << N) - 1 = 芯片容量（字节数）
   ★ 这些值在写入/读取时用于判断地址是否越界
   ==================================================================== */

// ★ AT24C01：1Kbit → 128 字节
// (1 << 7) - 1 = 128 - 1 = 127
#define AT24C01     ((1 << 7) - 1)

// ★ AT24C02：2Kbit → 256 字节
// (1 << 8) - 1 = 256 - 1 = 255
#define AT24C02     ((1 << 8) - 1)

// ★ AT24C04：4Kbit → 512 字节
// (1 << 9) - 1 = 512 - 1 = 511
#define AT24C04     ((1 << 9) - 1)

// ★ AT24C08：8Kbit → 1024 字节
// (1 << 10) - 1 = 1024 - 1 = 1023
#define AT24C08     ((1 << 10) - 1)

// ★ AT24C16：16Kbit → 2048 字节
// (1 << 11) - 1 = 2048 - 1 = 2047
#define AT24C16     ((1 << 11) - 1)

// ★ AT24C32：32Kbit → 4096 字节
// (1 << 12) - 1 = 4096 - 1 = 4095
#define AT24C32     ((1 << 12) - 1)

// ★ AT24C64：64Kbit → 8192 字节
// (1 << 13) - 1 = 8192 - 1 = 8191
#define AT24C64     ((1 << 13) - 1)

// ★ AT24C128：128Kbit → 16384 字节
// (1 << 14) - 1 = 16384 - 1 = 16383
#define AT24C128    ((1 << 14) - 1)

// ★ AT24C256：256Kbit → 32768 字节
// (1 << 15) - 1 = 32768 - 1 = 32767
#define AT24C256    ((1 << 15) - 1)

/* ====================================================================
   板载 24Cxx 型号选择
   ==================================================================== */

// ★ 本实验使用的 EEPROM 型号：AT24C02（256 字节）
// 如果更换了不同容量的 EEPROM，只需修改这个宏即可
// 其他代码不需要改动（因为地址参数用的是 uint16_t，兼容所有型号）
#define EE_TYPE     AT24C02

/* ====================================================================
   AT24Cxx 驱动函数声明
   ==================================================================== */

/**
 * @brief   初始化 AT24Cxx（24C02）
 * @note    主要是初始化底层的 IIC 硬件或 GPIO
 *          对于模拟 IIC，调用 iic_init() 初始化 SCL/SDA 引脚
 *          对于硬件 IIC，调用 HAL_I2C_Init() 初始化 I2C 外设
 * @param   无
 * @retval  无
 */
void at24cxx_init(void);

/**
 * @brief   检测 AT24Cxx 芯片是否正常
 * @note    原理：向设备地址 0xA0 发送一个字节（无数据），
 *          如果能收到 ACK 应答，说明芯片存在且正常工作
 *          如果不能收到 ACK，说明芯片损坏、未焊接或地址不对
 * @param   无
 * @retval  0：芯片正常，1：芯片异常
 */
uint8_t at24cxx_check(void);

/**
 * @brief   从 AT24Cxx 指定地址读取一字节数据
 * @param   addr: 要读取的地址（0~255 或 0~65535，取决于芯片型号）
 * @retval  读取到的数据（1 字节）
 * @note    内部流程：
 *          ① 发送起始信号
 *          ② 发送设备地址（写方向，0xA0）
 *          ③ 发送要读取的地址（addr）
 *          ④ 发送重复起始信号
 *          ⑤ 发送设备地址（读方向，0xA1）
 *          ⑥ 从 EEPROM 读取 1 字节数据（发送 NACK 结束）
 *          ⑦ 发送停止信号
 */
uint8_t at24cxx_read_one_byte(uint16_t addr);

/**
 * @brief   往 AT24Cxx 指定地址写入一字节数据
 * @param   addr: 要写入的地址（0~255 或 0~65535，取决于芯片型号）
 * @param   data: 要写入的数据（1 字节）
 * @retval  无
 * @note    内部流程：
 *          ① 发送起始信号
 *          ② 发送设备地址（写方向，0xA0）
 *          ③ 发送要写入的地址（addr）
 *          ④ 发送要写入的数据（data）
 *          ⑤ 发送停止信号
 *          
 *          ★ 注意：写入完成后，EEPROM 需要时间将数据编程到内部 Flash
 *          通常需要等待 5~10ms（page write cycle time）
 *          在此期间 EEPROM 不会响应新的 IIC 命令
 */
void at24cxx_write_one_byte(uint16_t addr, uint8_t data);

/**
 * @brief   从 AT24Cxx 指定地址开始读取指定长度的数据
 * @param   addr:    起始地址
 * @param   pbuf:    存放读取数据的缓冲区指针
 * @param   datalen: 要读取的数据长度（字节数）
 * @retval  无
 * @note    内部流程：循环调用 at24cxx_read_one_byte()
 *          每次读取一个字节，地址自动递增
 *          
 *          ★ 注意：如果读取长度超过芯片容量，可能会读到无效数据
 *          调用前应确保 (addr + datalen) <= EE_TYPE 容量
 */
void at24cxx_read(uint16_t addr, uint8_t *pbuf, uint16_t datalen);

/**
 * @brief   往 AT24Cxx 指定地址开始写入指定长度的数据
 * @param   addr:    起始地址
 * @param   pbuf:    要写入的数据缓冲区指针
 * @param   datalen: 要写入的数据长度（字节数）
 * @retval  无
 * @note    内部流程：循环调用 at24cxx_write_one_byte()
 *          每次写入一个字节，地址自动递增
 *          
 *          ★ 重要：AT24C02 的页写入限制！
 *          AT24C02 的页大小为 8 字节（同一页地址的高 5 位相同）
 *          如果一次性写入超过 8 字节，地址会自动回绕到页开头！
 *          建议：跨页写入时分段写入，或每次只写 1 个字节
 *          
 *          本函数逐字节写入，每写一个字节后延时 5ms
 *          虽然速度较慢，但不会出现页回绕问题
 *          
 *          ★ 注意：如果写入长度超过芯片容量，会覆盖到地址 0
 *          调用前应确保 (addr + datalen) <= EE_TYPE 容量
 */
void at24cxx_write(uint16_t addr, uint8_t *pbuf, uint16_t datalen);

#endif    // 结束 __24CXX_H 的条件编译