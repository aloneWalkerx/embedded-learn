/**
 ****************************************************************************************************
 * @file        iic.c
 * @brief       软件 I2C 驱动（开漏输出 + ACK 检测 + 总线恢复）
 * @note        本文件每一行的写法都直接对应 I2C 协议规定：
 *              规定1：开漏输出 + 外部上拉，总线为线与逻辑
 *              规定2：SCL 高时 SDA 必须稳定，SCL 低时 SDA 才允许变化
 *              规定3：START = SCL 高时 SDA 下降；STOP = SCL 高时 SDA 上升
 *              规定4：每 8 位数据后跟 1 位 ACK（接收方拉低 SDA = ACK）
 *              规定5：每根线电平变化后必须延时，满足时序和总线充电时间
 *              规定6：每个函数结束时把总线留在"下一步能正常工作"的状态
 ****************************************************************************************************
 */

#include "./BSP/IIC/iic.h"                          /* 包含引脚宏、函数声明、IIC_SDA_ReadPin 宏 */
#include "./SYSTEM/delay/delay.h"                   /* 包含 delay_us，iic_delay 内部要调用 */

/* ═══════════════════════════════════════════════════════════════
 *  内部延时函数
 *  规定5：每次电平变化后必须延时
 *  作用：① 满足 I2C 协议规定的最小时序（tLOW / tHIGH / tSU:DAT）
 *        ② 给开漏总线的上升沿留出上拉电阻充电时间
 *        ③ 给从机采样/响应时间
 *  参数：2us 约对应 250kHz，是标准模式和快速模式之间的折中值
 *  注意：延时太短通信不稳，太长速率下降，2us 是常见经验值
 * ═══════════════════════════════════════════════════════════════ */
static void iic_delay(void) {
    delay_us(2);
}

/* ═══════════════════════════════════════════════════════════════
 *  IIC 初始化
 *  规定1：开漏输出 + 上拉
 *  规定6：初始化结束时把总线留在空闲状态
 * ═══════════════════════════════════════════════════════════════ */
void iic_init(void) {
    GPIO_InitTypeDef gpio_init_struct = {0};        /* 结构体清零，避免未初始化字段是栈上垃圾值 */

    IIC_SCL_GPIO_CLK_ENABLE();                      /* 使能 GPIOB 时钟（STM32 必须，不开时钟写寄存器无效） */
    IIC_SDA_GPIO_CLK_ENABLE();                      /* 两个宏展开都是 GPIOB，重复但无害 */

    /* 规定1：必须开漏输出。开漏时"输出高"实际是"释放"，由外部上拉电阻拉高 */
    gpio_init_struct.Pin = IIC_SCL_GPIO_PIN | IIC_SDA_GPIO_PIN; /* 同时选中 SCL 和 SDA 两个引脚 */
    gpio_init_struct.Mode = GPIO_MODE_OUTPUT_OD;    /* 开漏输出，I2C 强制要求 */
    gpio_init_struct.Pull = GPIO_NOPULL;            /* 不用内部上拉，靠外部 4.7kΩ 上拉 */
    gpio_init_struct.Speed = GPIO_SPEED_FREQ_HIGH;  /* 高速，让边沿更陡 */

    HAL_GPIO_Init(IIC_SCL_GPIO_PORT, &gpio_init_struct); /* 配置 GPIOB 上的两个引脚 */

    iic_bus_recovery();                             /* 先恢复总线：应对 MCU 复位时从机把 SDA 拉死的场景 */
    iic_stop();                                     /* 再发停止条件：确保总线回到空闲状态（SCL=H，SDA=H） */
}

/* ═══════════════════════════════════════════════════════════════
 *  总线恢复
 *  规定：从机把 SDA 拉低不放时，主机无法产生 STOP → 总线死锁
 *  原理：翻转 9 个 SCL 脉冲，让从机把当前字节发完（8 位 + 1 位 ACK = 9 个周期），
 *        从机发完后会释放 SDA，进入等待下一个 START 的状态
 *        最后再发 STOP，让所有从机明确回到空闲状态
 * ═══════════════════════════════════════════════════════════════ */
void iic_bus_recovery(void) {
    uint8_t i;

    IIC_SDA(1);                                     /* 主机先释放 SDA，把控制权让给从机/上拉电阻 */
    iic_delay();                                    /* 延时，等 SDA 被上拉电阻拉到稳定高电平 */

    for (i = 0; i < 9; i++) {                       /* 规定：9 个 SCL 脉冲 = 1 字节 + 1 位 ACK 的周期数 */
        IIC_SCL(0);                                 /* 拉低 SCL，进入"允许变化"窗口 */
        iic_delay();
        IIC_SCL(1);                                 /* 拉高 SCL，产生上升沿，从机状态机推进一位 */
        iic_delay();
    }

    iic_stop();                                     /* 发 STOP，明确告诉所有从机：传输结束，总线空闲 */
}

/* ═══════════════════════════════════════════════════════════════
 *  起始条件（START）
 *  规定3：SCL 高时，SDA 从高变低 = START
 *  规定6：结束时必须把 SCL 拉低，把总线留在"允许改 SDA"的状态
 * ═══════════════════════════════════════════════════════════════ */
void iic_start(void) {
    IIC_SDA(1);                                     /* ① 释放 SDA 为高，保证后面有 H→L 的跳变 */
    IIC_SCL(1);                                     /* ② 释放 SCL 为高，保证跳变发生在 SCL 高电平时 */
    /*    注意：顺序不能反！先 SCL 后 SDA 会被误认为 STOP */
    iic_delay();                                    /* ③ 等两根线稳定为高（总线充电时间） */

    IIC_SDA(0);                                     /* ④ SCL 高时拉低 SDA → 这就是 START 定义 */
    iic_delay();                                    /* ⑤ 让从机识别到这个下降沿，切到"接收地址"模式 */

    IIC_SCL(0);                                     /* ⑥ 拉低 SCL，切换到"允许改 SDA"状态 */
    /*    规定2：SCL 高时 SDA 必须稳定，SCL 低时才能改 SDA */
    /*    如果不拉低，下一步发数据改 SDA 会误触发 STOP */
    iic_delay();                                    /* ⑦ 准备发送第一位数据 */
}

/* ═══════════════════════════════════════════════════════════════
 *  停止条件（STOP）
 *  规定3：SCL 高时，SDA 从低变高 = STOP
 *  规定6：结束时总线回到空闲（SCL=H，SDA=H）
 * ═══════════════════════════════════════════════════════════════ */
void iic_stop(void) {
    IIC_SDA(0);                                     /* ① 先拉低 SDA，保证后面有 L→H 的跳变 */
    iic_delay();                                    /* ② 等 SDA 稳定为低 */

    IIC_SCL(1);                                     /* ③ 拉高 SCL，进入"SCL 高"窗口 */
    iic_delay();                                    /* ④ 等 SCL 稳定为高（总线充电） */

    IIC_SDA(1);                                     /* ⑤ SCL 高时拉高 SDA → 这就是 STOP 定义 */
    iic_delay();                                    /* ⑥ 等从机识别，总线回到空闲（SCL=H，SDA=H） */
}

/* ═══════════════════════════════════════════════════════════════
 *  发送一个字节
 *  规定2：SCL 低时改 SDA，SCL 高时从机采样
 *  规定4：发送 MSB first（高位先行），8 位发完后跟 1 位 ACK
 * ═══════════════════════════════════════════════════════════════ */
uint8_t iic_send_slave_byte(uint8_t data) {
    uint8_t t;

    for (t = 0; t < 8; t++) {                       /* 循环 8 次，每次发一位 */
        IIC_SDA((data & 0x80) >> 7);                /* ① 取 data 的 bit7，放到 SDA 上 */
        /*    data & 0x80 保留 bit7，>>7 挪到 bit0 位得到 0/1 */
        /*    规定4：MSB first，从最高位开始 */
        /*    此时 SCL=0（函数进入前状态），改 SDA 合法 */
        iic_delay();                                /* ② 等 SDA 稳定 */

        IIC_SCL(1);                                 /* ③ 拉高 SCL，产生上升沿 */
        /*    规定2：从机在 SCL 高电平时采样 SDA */
        iic_delay();                                /* ④ 保持 SCL 高电平（满足 tHIGH） */

        IIC_SCL(0);                                 /* ⑤ 拉低 SCL，进入"允许改 SDA"窗口 */
        /*    规定2：SCL 低时 SDA 才允许变化 */
        iic_delay();                                /* ⑥ 保持 SCL 低电平（满足 tLOW） */

        data <<= 1;                                 /* ⑦ 左移，把下一位挪到 bit7，供下轮循环取 */
    }

    IIC_SDA(1);                                     /* ⑧ 释放 SDA，把控制权交给从机 */

    return iic_wait_slave_ack();                    /* ★ 内部自动等 ACK，返回 0=ACK，1=NACK */

}

/* ═══════════════════════════════════════════════════════════════
 *  等待从机应答（ACK 检测）
 *  规定4：每 8 位数据后第 9 个 SCL 脉冲用于 ACK
 *         接收方在 SCL 高时拉低 SDA = ACK；保持高 = NACK
 *  原理：主机释放 SDA 把控制权交给从机 → 拉高 SCL 产生第 9 个脉冲
 *        → 在 SCL 高时反复读 SDA → 读到低 = ACK，超时 = NACK
 * ═══════════════════════════════════════════════════════════════ */
uint8_t iic_wait_slave_ack(void) {
    uint8_t wait_time = 0;                          /* 超时计数器 */
    IIC_SDA(1);                                     /* ① 释放 SDA，把控制权交给从机 */
    /*    主机刚才发完 8 位，最后一位可能把 SDA 拉低了 */
    /*    不释放的话，从机想拉低也拉不低，无法表达 ACK */
    iic_delay();                                    /* ② 等 SDA 稳定 */

    IIC_SCL(1);                                     /* ③ 拉高 SCL，产生第 9 个脉冲 */
    iic_delay();                                    /* ④ 给从机一点反应时间 */

    while (IIC_SDA_READ != 0) {                     /* ⑤ 在 SCL 高电平期间反复读 SDA */
        /*    从机拉低 SDA 需要几微秒，不能立即判断 */
        wait_time++;                                /*    超时计数 +1 */
        if (wait_time > 250) {                      /* ⑥ 超时保护：250 次 × 2us ≈ 500us */
            IIC_SDA(0);
            iic_delay();
            return 1;                               /* 返回 NACK，让上层决定是否 iic_stop() */
        }
        iic_delay();                                /* ⑦ 每次循环延时，避免超时时间太短 */
    }

    IIC_SCL(0);                                     /* ⑧ 收到 ACK，拉低 SCL 结束第 9 个脉冲 */
    /*    规定6：把总线留在"允许改 SDA"的状态 */
    iic_delay();
    return 0;                                       /* 返回 0 = ACK */
}

/* ═══════════════════════════════════════════════════════════════
 *  读取一个字节
 *  规定2：SCL 低时从机准备数据，SCL 高时主机采样
 *  规定4：读完后主机发 ACK（继续读）或 NACK（读完）
 *  原理：读数据时是"从机驱动 SDA，主机产生时钟"
 *        主机必须释放 SDA，否则和从机抢总线
 * ═══════════════════════════════════════════════════════════════ */
uint8_t iic_read_slave_byte(uint8_t ack) {
    uint8_t i;
    uint8_t receive = 0;

    IIC_SDA(1);                                     /* ① 释放 SDA，让从机驱动 */
    /*    读操作时是从机发数据，主机不能拉 SDA */

    for (i = 0; i < 8; i++) {                       /* 循环 8 次，每次读一位 */
        receive <<= 1;                              /* ② 左移，给新读到的位腾位置 */
        /*    MSB first，最高位先读到 */

        IIC_SCL(1);                                 /* ③ 拉高 SCL，从机在此刻输出数据 */
        iic_delay();                                /* ④ 等从机把数据放到 SDA 上并稳定 */

        if (IIC_SDA_READ) {                         /* ⑤ 在 SCL 高电平期间采样 SDA */
            receive++;                              /*    读到高电平，最低位 +1 */
            /*    等价于 receive |= 1 */
        }

        IIC_SCL(0);                                 /* ⑥ 拉低 SCL，让从机准备下一位 */
        iic_delay();                                /* ⑦ 满足 tLOW */
    }

    if (ack) {                                      /* ⑧ 根据调用者传入的 ack 参数决定应答方式 */
        iic_master_ack();                           /*    ack=1：还有后续数据要读，发 ACK */
    } else {
        iic_master_nack();                          /*    ack=0：最后一个字节，发 NACK 告诉从机停止 */
    }

    return receive;                                 /* ⑨ 返回读到的字节 */
}

/* ═══════════════════════════════════════════════════════════════
 *  主机发送 ACK
 *  用途：主机读数据时，读完一个字节后拉低 SDA 表示"我收到了，请继续发"
 *  规定4：接收方在 SCL 高电平时拉低 SDA = ACK
 * ═══════════════════════════════════════════════════════════════ */
void iic_master_ack(void) {
    IIC_SDA(0);                                     /* ① 拉低 SDA，准备发出 ACK */
    iic_delay();                                    /* ② 等 SDA 稳定 */
    IIC_SCL(1);                                     /* ③ 拉高 SCL，从机在此刻采样到 ACK */
    iic_delay();                                    /* ④ 保持 SCL 高电平 */
    IIC_SCL(0);                                     /* ⑤ 拉低 SCL，结束 ACK 周期 */
    iic_delay();
    IIC_SDA(1);                                     /* ⑥ 释放 SDA，准备下一步（从机要发下一个字节） */
    iic_delay();
}

/* ═══════════════════════════════════════════════════════════════
 *  主机发送 NACK
 *  用途：主机读最后一个字节后保持 SDA 高表示"不要继续发了"
 *  规定4：接收方在 SCL 高电平时保持 SDA 高 = NACK
 *  与 ACK 唯一区别：SDA 保持高而不是拉低
 * ═══════════════════════════════════════════════════════════════ */
void iic_master_nack(void) {
    IIC_SDA(1);                                     /* ① 保持 SDA 高（= NACK） */
    iic_delay();
    IIC_SCL(1);                                     /* ② 拉高 SCL，从机采样到 NACK */
    iic_delay();
    IIC_SCL(0);                                     /* ③ 拉低 SCL，结束 NACK 周期 */
    iic_delay();
}
